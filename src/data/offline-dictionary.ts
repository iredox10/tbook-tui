export function lookupOffline(word: string): string | null {
    const entry = raw[word.toLowerCase()]
    if (!entry) return null
    const [definition, pos] = entry.split("|")
    let result = `📖 ${word}`
    if (pos) result += `  [${pos}]`
    result += `\n   1. ${definition || entry}\n   (offline dictionary)`
    return result
}

export function wordExistsOffline(word: string): boolean {
    return word.toLowerCase() in raw
}
